function c=makeCandidate(uavIndex,mode,insertAfterSeqIndex,currentTargetSeqIndex, ...
    newTaskId,baseline,proposed,uav,demand,cfg)

c=emptyCandidate();
c.uav=uavIndex;
c.mode=mode;
c.insertAfterSeqIndex=insertAfterSeqIndex;
c.currentTargetSeqIndex=currentTargetSeqIndex;

if strcmp(mode,'immediate')
    c.insertAfterTask=NaN; % virtual current-state insertion point
    c.insertBeforeTask=baseline.remainingTaskIds(1);
else
    c.insertAfterTask=NaN;
    c.insertBeforeTask=NaN;
end

c.deltaDistanceM=proposed.distanceM-baseline.distanceM;
c.deltaEnergyJ=proposed.energyJ-baseline.energyJ;
c.deltaLatenessS=proposed.latenessS-baseline.latenessS;
c.residualCapacityKg=uav.remainLoad-demand;
c.residualEnduranceS=cfg.uav.maxEndurance-proposed.finishTimeS;
c.baselineRemainingTimeS=baseline.remainingTimeS;
c.proposedRemainingTimeS=proposed.remainingTimeS;

payloadOK=c.residualCapacityKg>=-cfg.reallocation.feasibilityTolerance;
timeOK=c.residualEnduranceS>=-cfg.reallocation.feasibilityTolerance;
c.feasible=payloadOK && timeOK && proposed.valid;

Dref=max(cfg.reallocation.distanceRefM,eps);
Tref=max(cfg.reallocation.latenessRefS,eps);

c.distanceTerm=c.deltaDistanceM/Dref;
c.capacityTerm=max(0,c.residualCapacityKg)/cfg.uav.capacity;
c.enduranceTerm=max(0,c.residualEnduranceS)/cfg.uav.maxEndurance;
c.latenessTerm=max(0,c.deltaLatenessS)/Tref;

c.score= -cfg.reallocation.wDistance*c.distanceTerm ...
         +cfg.reallocation.wCapacity*c.capacityTerm ...
         +cfg.reallocation.wEndurance*c.enduranceTerm ...
         -cfg.reallocation.wLateness*c.latenessTerm;

% Preserve newTaskId in a harmless way for debugging if needed.
if newTaskId<0 %#ok<UNRCH>
    c.score=-inf;
end
end

function baseline=computeCurrentRemainingSchedule(uav,sequence,Target,Cost,simTime,cfg)
currentIdx=uav.legIndex+1;
assert(currentIdx<=numel(sequence),'Invalid UAV legIndex relative to route sequence.');
[firstD,firstE,firstT]=remainingCurrentLegMetrics(uav,cfg);
remainingIds=sequence(currentIdx:end);
baseline=buildScheduleFromCurrent(firstD,firstE,firstT,remainingIds,Target,Cost,simTime,cfg);
baseline.firstLegDistanceM=firstD;
baseline.firstLegEnergyJ=firstE;
baseline.firstLegTimeS=firstT;
baseline.remainingTaskIds=remainingIds;
end

function S=buildScheduleFromCurrent(firstD,firstE,firstT,remainingIds,Target,Cost,simTime,cfg)
S=struct('valid',false,'distanceM',inf,'energyJ',inf,'remainingTimeS',inf, ...
    'finishTimeS',inf,'latenessS',inf,'arrivalTaskIds',[],'arrivalTimesS',[], ...
    'remainingArrivalTimesS',nan(size(remainingIds)));

if isempty(remainingIds)
    S.valid=true;
    S.distanceM=0;
    S.energyJ=0;
    S.remainingTimeS=0;
    S.finishTimeS=simTime;
    S.latenessS=0;
    return;
end

elapsed=firstT;
distance=firstD;
energy=firstE;
lateness=0;
arrivalIds=[];
arrivalTimes=[];

firstTask=remainingIds(1);
arrivalTime=simTime+elapsed;
if firstTask>0
    lateness=lateness+taskLatenessS(firstTask,arrivalTime,Target);
    arrivalIds(end+1)=firstTask; %#ok<AGROW>
    arrivalTimes(end+1)=arrivalTime; %#ok<AGROW>
end
S.remainingArrivalTimesS(1)=arrivalTime;

for r=1:numel(remainingIds)-1
    a=remainingIds(r)+1;
    b=remainingIds(r+1)+1;
    if a<1 || b<1 || a>size(Cost.D,1) || b>size(Cost.D,2) || ...
            ~Cost.Success(a,b) || ~isfinite(Cost.D(a,b)) || ~isfinite(Cost.T(a,b))
        return;
    end

    distance=distance+Cost.D(a,b);
    energy=energy+Cost.E(a,b);
    elapsed=elapsed+Cost.T(a,b);

    task=remainingIds(r+1);
    S.remainingArrivalTimesS(r+1)=simTime+elapsed;
    if task>0
        arrivalTime=S.remainingArrivalTimesS(r+1);
        lateness=lateness+taskLatenessS(task,arrivalTime,Target);
        arrivalIds(end+1)=task; %#ok<AGROW>
        arrivalTimes(end+1)=arrivalTime; %#ok<AGROW>
    end
end

S.valid=true;
S.distanceM=distance;
S.energyJ=energy;
S.remainingTimeS=elapsed;
S.finishTimeS=simTime+elapsed;
S.latenessS=lateness;
S.arrivalTaskIds=arrivalIds;
S.arrivalTimesS=arrivalTimes;

% Silence cfg unused warning in older MATLAB releases while keeping the
% function signature explicit for future deadline-policy extensions.
if cfg.dynamic.defaultTaskDueTime<0 %#ok<UNRCH>
    S.valid=false;
end
end

function S=buildAfterTaskInsertionSchedule(baseline,d,newTaskId,Target,Cost,simTime,cfg)
S=baseline;
S.valid=false;

fromTask=d.insertAfterTask;
toTask=d.insertBeforeTask;
a=fromTask+1;
b=toTask+1;
n=newTaskId+1;

if any([a,b,n] < 1) || any([a,b,n] > size(Cost.D,1)) || ...
        ~Cost.Success(a,n) || ~Cost.Success(n,b) || ~Cost.Success(a,b)
    return;
end

oldD=Cost.D(a,b);
oldE=Cost.E(a,b);
oldT=Cost.T(a,b);
newD=Cost.D(a,n)+Cost.D(n,b);
newE=Cost.E(a,n)+Cost.E(n,b);
newT=Cost.T(a,n)+Cost.T(n,b);
if ~all(isfinite([oldD,oldE,oldT,newD,newE,newT]))
    return;
end

relFrom=d.insertAfterSeqIndex-d.currentTargetSeqIndex+1;
relTo=relFrom+1;
if relFrom<1 || relFrom>numel(baseline.remainingTaskIds) || ...
        relTo<1 || relTo>numel(baseline.remainingTaskIds)
    return;
end

timeAtFrom=baseline.remainingArrivalTimesS(relFrom);
if ~isfinite(timeAtFrom)
    return;
end

deltaT=newT-oldT;
deltaL=taskLatenessS(newTaskId,timeAtFrom+Cost.T(a,n),Target);
for rr=relTo:numel(baseline.remainingTaskIds)
    task=baseline.remainingTaskIds(rr);
    if task<=0
        continue;
    end
    oldArrival=baseline.remainingArrivalTimesS(rr);
    if ~isfinite(oldArrival)
        return;
    end
    deltaL=deltaL + ...
        taskLatenessS(task,oldArrival+deltaT,Target) - ...
        taskLatenessS(task,oldArrival,Target);
end

S.distanceM=baseline.distanceM + newD - oldD;
S.energyJ=baseline.energyJ + newE - oldE;
S.remainingTimeS=baseline.remainingTimeS + deltaT;
S.finishTimeS=baseline.finishTimeS + deltaT;
S.latenessS=baseline.latenessS + deltaL;
S.remainingTaskIds=[baseline.remainingTaskIds(1:relFrom), ...
    newTaskId,baseline.remainingTaskIds(relTo:end)];
S.remainingArrivalTimesS=[baseline.remainingArrivalTimesS(1:relFrom), ...
    timeAtFrom+Cost.T(a,n),baseline.remainingArrivalTimesS(relTo:end)+deltaT];
positiveMask=S.remainingTaskIds>0;
S.arrivalTaskIds=S.remainingTaskIds(positiveMask);
S.arrivalTimesS=S.remainingArrivalTimesS(positiveMask);
S.valid=true;

if cfg.dynamic.defaultTaskDueTime<0 || simTime<0 %#ok<UNRCH>
    S.valid=false;
end
end

function L=taskLatenessS(taskId,arrivalTimeS,Target)
node=taskId+1;
if node<1 || node>size(Target,1) || size(Target,2)<5 || Target(node,5)<=0
    L=0;
else
    L=max(0,arrivalTimeS-60*Target(node,5));
end
end

function [D,E,T]=remainingCurrentLegMetrics(uav,cfg)
path=uav.path;
if isempty(path) || uav.pathIndex>=size(path,1)
    D=0; E=0; T=0; return;
end
pts=[uav.currentPos;path(uav.pathIndex+1:end,:)];
[D,E]=polylineMetrics(pts,cfg);
T=D/cfg.uav.speed;
end

function P=planCurrentToDynamicTask(currentPos,targetPos,map,cfg)
t=tic;
R=planTerrainPath(currentPos,targetPos,map,cfg,false);
path=R.path;

% planTerrainPath operates on DEM grid nodes, so a mid-edge fractional
% current position is rounded internally. Prepend the exact current state
% to preserve the small remaining connector segment in the dynamic cost.
if isempty(path)
    error('No dynamic diversion path was generated.');
end
if norm(path(1,:)-currentPos)>cfg.path.duplicateTolerance
    path=[currentPos;path];
else
    path(1,:)=currentPos;
end
[D,E]=polylineMetrics(path,cfg);

P=struct();
P.path=path;
P.D=D;
P.E=E;
P.T=D/cfg.uav.speed;
P.runtimeS=toc(t);
end

function [D,E]=polylineMetrics(path,cfg)
if size(path,1)<2
    D=0; E=0; return;
end
dRow=diff(path(:,1))*cfg.map.resolution;
dCol=diff(path(:,2))*cfg.map.resolution;
dH=hypot(dRow,dCol);
dZ=diff(path(:,3));
d3=hypot(dH,dZ);
D=sum(d3);
E=sum(cfg.path.muHorizontal*dH + cfg.path.muVertical*abs(dZ));
end

function out=stripCandidatePaths(in)
out=in;
if isempty(out), return; end
out=rmfield(out,'diversionPath');
end

%% ========================================================================
%  Communication model (validated v2.5 implementation)
%  ========================================================================
function net=computeCommunication(UAV,map,cfg)
%COMPUTECOMMUNICATION Terrain-dependent communication graph.
%
% For each UAV pair (i,j):
%   d_ij = ||p_i-p_j||_2                           [m]
%   z_ij(lambda) = z_i + lambda(z_j-z_i)
%   h_obs = max_lambda [H(x(lambda),y(lambda))-z_ij(lambda)]_+
%   d_th = d_max/(1+kappa*h_obs^2)
% A direct physical link exists iff d_ij <= d_th. Multi-hop reachability
% and shortest hop count are then derived from the direct-link graph.

n=numel(UAV);
directAdj=eye(n)>0;
distance3DM=zeros(n);
horizontalDistanceM=zeros(n);
obstructionHeightM=zeros(n);
effectiveThresholdM=cfg.comm.maxDistanceM*ones(n);
losClear=true(n);
rangeScreenPassed=true(n);

for i=1:n
    for j=i+1:n
        p1=UAV(i).currentPos;
        p2=UAV(j).currentPos;

        dRowM=cfg.map.resolution*(p2(1)-p1(1));
        dColM=cfg.map.resolution*(p2(2)-p1(2));
        dHoriz=hypot(dRowM,dColM);
        d3=hypot(dHoriz,p2(3)-p1(3));

        distance3DM(i,j)=d3; distance3DM(j,i)=d3;
        horizontalDistanceM(i,j)=dHoriz; horizontalDistanceM(j,i)=dHoriz;

        % Always evaluate the terrain profile for diagnostics, even when
        % nominal range alone is already insufficient.
        if dHoriz<=eps
            hObs=0;
        else
            nSamples=max(2,ceil(dHoriz/cfg.comm.losSampleSpacingM)+1);
            lambda=linspace(0,1,nSamples);
            rows=p1(1)+lambda*(p2(1)-p1(1));
            cols=p1(2)+lambda*(p2(2)-p1(2));
            terrain=interp2(map,cols,rows,'linear');
            if any(~isfinite(terrain))
                error('simulateDynamicMission:CommunicationTerrainSample', ...
                    'Nonfinite DEM sample on UAV %d-%d communication segment.',i,j);
            end
            zLine=p1(3)+lambda*(p2(3)-p1(3));
            hObs=max(0,max(terrain-zLine));
        end

        clearLOS=hObs<=cfg.comm.obstructionToleranceM;
        dTh=cfg.comm.maxDistanceM/(1+cfg.comm.blockageAlphaPerM2*hObs^2);
        rangeOK=d3<=cfg.comm.maxDistanceM;
        link=d3<=dTh;

        directAdj(i,j)=link; directAdj(j,i)=link;
        obstructionHeightM(i,j)=hObs; obstructionHeightM(j,i)=hObs;
        effectiveThresholdM(i,j)=dTh; effectiveThresholdM(j,i)=dTh;
        losClear(i,j)=clearLOS; losClear(j,i)=clearLOS;
        rangeScreenPassed(i,j)=rangeOK; rangeScreenPassed(j,i)=rangeOK;
    end
end

% Shortest hop count on the undirected direct-link graph.
hopCount=inf(n);
hopCount(1:n+1:end)=0;
edgeMask=directAdj & ~eye(n);
hopCount(edgeMask)=1;
for k=1:n
    for i=1:n
        for j=1:n
            candidate=hopCount(i,k)+hopCount(k,j);
            if candidate<hopCount(i,j)
                hopCount(i,j)=candidate;
            end
        end
    end
end
reachability=isfinite(hopCount);

componentId=zeros(1,n);
componentCount=0;
for i=1:n
    if componentId(i)~=0, continue; end
    componentCount=componentCount+1;
    members=find(reachability(i,:));
    componentId(members)=componentCount;
end

net=struct();
net.directAdjacency=logical(directAdj);
net.reachability=logical(reachability);
net.hopCount=hopCount;
net.distance3DM=distance3DM;
net.horizontalDistanceM=horizontalDistanceM;
net.obstructionHeightM=obstructionHeightM;
net.effectiveThresholdM=effectiveThresholdM;
net.losClear=logical(losClear);
net.rangeScreenPassed=logical(rangeScreenPassed);
net.componentId=componentId;
net.numComponents=componentCount;
net.numDirectLinks=nnz(triu(directAdj,1));
end


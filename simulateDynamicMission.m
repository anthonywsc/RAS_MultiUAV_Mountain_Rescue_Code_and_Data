function results = simulateDynamicMission(data, cfg)
%SIMULATEDYNAMICMISSION Terrain-aware dynamic multi-UAV mission simulation.
% v2.9.1 event-driven local-reallocation hotfix:
%   1) retains the validated terrain-dependent communication model;
%   2) removes full dynamic row/column rebuilding of the terrain-cost
%      library and retains persistent task-edge caching;
%   3) enumerates all communication-reachable local insertion candidates,
%      but ranks them by a cheap optimistic bid upper bound before any new
%      DEMA* call;
%   4) exact terrain paths are generated lazily only while a candidate can
%      still beat the current incumbent (branch-and-bound stopping);
%   5) current-position-to-new-task paths are event-local because the UAV
%      state changes continuously and must not be stored as static edges;
%   6) feasibility explicitly checks payload capacity and total mission
%      endurance, while deadlines remain soft and enter the exact bid via
%      incremental lateness DeltaLambda;
%   7) after-task exact candidates update the current remaining schedule
%      incrementally instead of rebuilding the whole suffix every time;
%   8) the winning UAV/insertion pair maximizes the same normalized score
%
%       b = -w_D*DeltaD/D_ref
%           +w_C*C_res/C_max
%           +w_T*T_res/T_max
%           -w_L*DeltaLambda/T_ref .
%
% This is an event-driven local insertion auction. It uses communication-
% constrained bidding and insertion costs, but does not require full CBBA
% bundle construction or repeated consensus iterations.
%
% Public task IDs use base=0 and tasks=1,2,... . Cost-library node indices
% are MATLAB indices 1,2,..., with node = taskID+1.

assert(isfield(data,'Target'),'Missing field in initial data: Target');
assert(isfield(data,'map'),'Missing field in initial data: map');
assert(isfield(data,'bestRoute') || isfield(data,'RouteCell'), ...
    'Initial data must contain bestRoute or RouteCell.');

map = data.map;
Target = normalizeTargetMatrix(data.Target,cfg);
seq = extractSequences(data);
numUAV = numel(seq);

% Prefer the unified terrain-cost library generated by the v2.4+ ACO.
% A legacy input can still be used, but its initial terrain-cost library
% must then be rebuilt once before the dynamic simulation starts.
if isfield(data,'Cost') && isstruct(data.Cost)
    Cost = data.Cost;
    validateCostPrefix(Cost,Target);
else
    warning('simulateDynamicMission:MissingUnifiedCost', ...
        ['Input data does not contain the unified Cost library. Rebuilding ', ...
         'the initial directed terrain-cost library before simulation.']);
    Cost = buildTerrainCostLibrary(Target,map,cfg, ...
        'Resume',false,'Verbose',cfg.reallocation.costUpdateVerbose,'FailFast',true);
end
WayPoints = Cost.Paths;

UAV = initializeUAVs(seq,Target,Cost,map,cfg);

newTargets = cfg.dynamic.newTargets;
discovered = false(size(newTargets,1),1);
complete = false(numUAV,1);
trajectories = cell(numUAV,1);
for i=1:numUAV
    trajectories{i}=UAV(i).currentPos;
end

eventLog = struct([]);

plotState=[];
if cfg.plot.enable
    plotState=initializeDynamicPlot(map,Target,newTargets,UAV,cfg);
end

maxSteps=ceil(4*cfg.uav.maxEndurance/cfg.dynamic.timeStep);

% Communication history. Index 1 corresponds to t=0.
commTimeS=nan(maxSteps+1,1);
directHistory=false(numUAV,numUAV,maxSteps+1);
reachHistory=false(numUAV,numUAV,maxSteps+1);
hopHistory=nan(numUAV,numUAV,maxSteps+1);
numDirectLinks=zeros(maxSteps+1,1);
numComponents=zeros(maxSteps+1,1);

network=computeCommunication(UAV,map,cfg);
commTimeS(1)=0;
directHistory(:,:,1)=network.directAdjacency;
reachHistory(:,:,1)=network.reachability;
hopHistory(:,:,1)=network.hopCount;
numDirectLinks(1)=network.numDirectLinks;
numComponents(1)=network.numComponents;

step=0;
while ~all(complete)
    step=step+1;
    if step>maxSteps
        warning('Dynamic simulation reached safety step limit before all UAVs completed.');
        break;
    end

    % 1) Advance all UAVs to one common simulation instant.
    for i=1:numUAV
        if complete(i), continue; end
        [UAV(i),complete(i),seq{i},Target,WayPoints] = advanceOneUAV( ...
            UAV(i),seq{i},Target,WayPoints,map,cfg);
        trajectories{i}(end+1,:)=UAV(i).currentPos; %#ok<AGROW>
    end

    simTime=step*cfg.dynamic.timeStep;
    for i=1:numUAV
        UAV(i).time=simTime;
        if UAV(i).targetNode>=1 && UAV(i).targetNode<=size(Target,1)
            UAV(i).targetTime=Target(UAV(i).targetNode,5)*60-simTime;
        end
    end

    % 2) Build direct adjacency, multi-hop reachability, and hop counts.
    network=computeCommunication(UAV,map,cfg);
    histIdx=step+1;
    commTimeS(histIdx)=simTime;
    directHistory(:,:,histIdx)=network.directAdjacency;
    reachHistory(:,:,histIdx)=network.reachability;
    hopHistory(:,:,histIdx)=network.hopCount;
    numDirectLinks(histIdx)=network.numDirectLinks;
    numComponents(histIdx)=network.numComponents;

    % 3) Detect dynamic tasks and trigger one insertion auction per event.
    for discoverer=1:numUAV
        if complete(discoverer), continue; end

        for nt=1:size(newTargets,1)
            if discovered(nt), continue; end

            dGrid=norm(UAV(discoverer).currentPos(1:2)-newTargets(nt,1:2));
            if dGrid >= cfg.dynamic.discoveryRadius
                continue;
            end

            discovered(nt)=true;

            % Event-driven online update: append only the task metadata.
            % No complete row/column is planned here. Required terrain edges
            % are requested lazily by the insertion candidates below.
            [Target,newTaskId] = appendDynamicTarget(Target,newTargets(nt,:),cfg);
            Cost = expandCostMetadataOnDemand(Cost,Target,map,cfg);

            reallocationTimer=tic;
            [UAV,seq,event,Cost] = terrainAwareInsertionAuction( ...
                UAV,seq,Target,Cost,newTaskId,network.reachability, ...
                discoverer,complete,map,cfg,simTime);
            event.totalReallocationRuntimeS=toc(reallocationTimer);

            % Separate expensive DEMA* planning from the algebraic auction.
            event.costUpdateRuntimeS=event.terrainPlanningRuntimeS;
            event.auctionRuntimeS=max(0, ...
                event.totalReallocationRuntimeS-event.terrainPlanningRuntimeS);
            event.newCostPairs=event.taskEdgePlans;
            WayPoints=Cost.Paths;

            % Attach communication state existing at the event instant.
            event.time=simTime;
            event.targetIndex=nt;
            event.directAdjacency=double(network.directAdjacency);
            event.reachability=double(network.reachability);
            event.hopCount=network.hopCount;
            event.distance3DM=network.distance3DM;
            event.obstructionHeightM=network.obstructionHeightM;
            event.effectiveThresholdM=network.effectiveThresholdM;
            event.losClear=network.losClear;
            event.componentId=network.componentId;

            % Robust append: eventLog starts as a fieldless empty struct.
            % MATLAB does not allow direct assignment of a populated struct
            % into a fieldless struct array on all releases.
            if isempty(eventLog)
                eventLog=event;
            else
                eventLog(end+1)=event; %#ok<AGROW>
            end

            if cfg.plot.verbose
                if isfinite(event.winner)
                    fprintf(['t=%.0f s: UAV %d discovered dynamic task %d (task ID %d). ', ...
                        'Winner UAV %d, %s insertion, bid=%.4f, DeltaD=%.3f km, ', ...
                        'Delta lateness=%.2f min.\n'], ...
                        simTime,discoverer,nt,newTaskId,event.winner,event.insertMode, ...
                        event.score,event.selectedDeltaDistanceM/1000, ...
                        event.selectedDeltaLatenessS/60);
                else
                    fprintf(['t=%.0f s: UAV %d discovered dynamic task %d (task ID %d), ', ...
                        'but no communication-reachable resource-feasible insertion exists.\n'], ...
                        simTime,discoverer,nt,newTaskId);
                end
                fprintf(['  lazy terrain planning: %.2f s ', ...
                    '(%d task-edge plans, %d cache hits, %d current-state plans); ', ...
                    'auction algebra: %.3f s; total reallocation: %.2f s\n'], ...
                    event.costUpdateRuntimeS,event.taskEdgePlans, ...
                    event.taskEdgeCacheHits,event.currentStatePlans, ...
                    event.auctionRuntimeS,event.totalReallocationRuntimeS);
                fprintf(['  candidates: %d enumerated, %d exact evaluations, ', ...
                    '%d bound-pruned, %d optimistic-endurance-pruned.\n'], ...
                    event.totalEnumeratedCandidates,event.exactCandidateEvaluations, ...
                    event.boundPrunedCandidates, ...
                    event.optimisticEndurancePrunedCandidates);
            end
        end
    end

    if cfg.plot.enable
        updateDynamicPlot(plotState,UAV,trajectories,discovered,newTargets,cfg);
    end

    if cfg.plot.verbose && mod(step,60)==0
        fprintf('Dynamic simulation time: %.0f s | direct links: %d | components: %d\n', ...
            simTime,network.numDirectLinks,network.numComponents);
    end
end

nHist=min(step+1,maxSteps+1);
results=struct();
results.UAV=UAV;
results.Target=Target;
results.Cost=Cost;
results.WayPoints=WayPoints;
results.sequences=seq;
results.trajectories=trajectories;
results.eventLog=eventLog;
results.discovered=discovered;
results.completed=complete;
results.simulationTime=step*cfg.dynamic.timeStep;

results.communication=struct();
results.communication.timeS=commTimeS(1:nHist);
results.communication.directAdjacency=directHistory(:,:,1:nHist);
results.communication.reachability=reachHistory(:,:,1:nHist);
results.communication.hopCount=hopHistory(:,:,1:nHist);
results.communication.numDirectLinks=numDirectLinks(1:nHist);
results.communication.numComponents=numComponents(1:nHist);
results.communication.lastNetwork=network;
results.communication.model=struct( ...
    'maxDistanceM',cfg.comm.maxDistanceM, ...
    'blockageAlphaPerM2',cfg.comm.blockageAlphaPerM2, ...
    'losSampleSpacingM',cfg.comm.losSampleSpacingM, ...
    'obstructionToleranceM',cfg.comm.obstructionToleranceM);

results.reallocation=struct();
results.reallocation.model='Event-driven communication-constrained all-insertion auction with active-edge terrain-cost cache and incremental suffix scoring';
results.reallocation.selectionPolicy=cfg.reallocation.selectionPolicy;
results.reallocation.weights=[cfg.reallocation.wDistance, ...
    cfg.reallocation.wCapacity,cfg.reallocation.wEndurance,cfg.reallocation.wLateness];
results.reallocation.distanceRefM=cfg.reallocation.distanceRefM;
results.reallocation.latenessRefS=cfg.reallocation.latenessRefS;
results.reallocation.allowImmediateDiversion=cfg.reallocation.allowImmediateDiversion;
results.reallocation.onlineCostMode='candidate-lazy-bound-cache';
results.reallocation.onlineTaskEdgePlansAccumulated=Cost.OnlineTaskEdgePlansAccumulated;
results.reallocation.onlinePlanningRuntimeAccumulatedS=Cost.OnlinePlanningRuntimeAccumulated;
results.reallocation.summary=summarizeReallocationEvents(eventLog);

fprintf('\nFinal dynamic task sequences:\n');
for i=1:numUAV
    fprintf('UAV %d: %s\n',i,sprintf('%d ',seq{i}));
end
end

%% ========================================================================
%  Initial data and route handling
%  ========================================================================
function S=summarizeReallocationEvents(eventLog)
S=struct('numEvents',0,'numAssigned',0,'totalEnumeratedCandidates',0, ...
    'totalPotentialCandidates',0,'totalExactCandidateEvaluations',0, ...
    'totalBoundPrunedCandidates',0,'totalOptimisticEndurancePrunedCandidates',0, ...
    'meanExactEvaluationRatio',NaN,'totalTaskEdgePlans',0, ...
    'totalTaskEdgeCacheHits',0,'totalTaskEdgePlansAvoided',0, ...
    'totalTerrainPlanningRuntimeS',0,'totalReallocationRuntimeS',0);
if isempty(eventLog)
    return;
end

S.numEvents=numel(eventLog);
S.numAssigned=sum([eventLog.assigned]);
S.totalEnumeratedCandidates=sum([eventLog.totalEnumeratedCandidates]);
S.totalPotentialCandidates=sum([eventLog.potentialCandidateCount]);
S.totalExactCandidateEvaluations=sum([eventLog.exactCandidateEvaluations]);
S.totalBoundPrunedCandidates=sum([eventLog.boundPrunedCandidates]);
S.totalOptimisticEndurancePrunedCandidates= ...
    sum([eventLog.optimisticEndurancePrunedCandidates]);
ratios=[eventLog.exactEvaluationRatio];
S.meanExactEvaluationRatio=mean(ratios(isfinite(ratios)));
S.totalTaskEdgePlans=sum([eventLog.taskEdgePlans]);
S.totalTaskEdgeCacheHits=sum([eventLog.taskEdgeCacheHits]);
S.totalTaskEdgePlansAvoided=sum([eventLog.taskEdgePlansAvoided]);
S.totalTerrainPlanningRuntimeS=sum([eventLog.terrainPlanningRuntimeS]);
S.totalReallocationRuntimeS=sum([eventLog.totalReallocationRuntimeS]);
end

function Target=normalizeTargetMatrix(Target,cfg)
if size(Target,2)<4
    error('Target must contain at least [row col z demand].');
end
if size(Target,2)<5
    Target(:,5)=cfg.dynamic.defaultTaskDueTime;
    Target(1,5)=0;
end
end

function seq=extractSequences(data)
if isfield(data,'RouteCell') && ~isempty(data.RouteCell)
    seq=data.RouteCell(:).';
    return;
end
seq=routeToSequences(data.bestRoute);
end

function seq=routeToSequences(route)
zeroIdx=find(route==0);
seq={};
for k=1:numel(zeroIdx)-1
    block=route(zeroIdx(k):zeroIdx(k+1));
    if numel(block)>2
        seq{end+1}=block; %#ok<AGROW>
    end
end
end

function validateCostPrefix(Cost,Target)
assert(isfield(Cost,'TargetPosition') && isfield(Cost,'D') && ...
    isfield(Cost,'E') && isfield(Cost,'T') && isfield(Cost,'Paths') && ...
    isfield(Cost,'Success'),'Invalid unified Cost structure.');
n=size(Target,1);
assert(size(Cost.D,1)==n,'Cost node count does not match the current Target array.');
assert(isequaln(Cost.TargetPosition,Target(:,1:3)), ...
    'Cost.TargetPosition does not match Target(:,1:3).');
end

function UAV=initializeUAVs(seq,Target,Cost,map,cfg)
numUAV=numel(seq);
UAV=repmat(struct(),numUAV,1);
base=cfg.uav.baseIndex;

for i=1:numUAV
    s=seq{i};
    tasks=s(s>0);
    demand=sum(Target(tasks+1,4));

    plannedTime=0;
    for k=1:numel(s)-1
        plannedTime=plannedTime+Cost.T(s(k)+1,s(k+1)+1);
    end

    UAV(i).time=0;
    UAV(i).currentPos=[base(1),base(2),map(base(1),base(2))+cfg.uav.baseClearance];
    UAV(i).remainLoad=cfg.uav.capacity-demand;
    UAV(i).remainTime=cfg.uav.maxEndurance-plannedTime;
    UAV(i).legIndex=1;
    UAV(i).targetNode=s(2)+1;
    UAV(i).targetTime=Target(UAV(i).targetNode,5)*60;
    UAV(i).pathIndex=1;
    UAV(i).path=Cost.Paths{1,UAV(i).targetNode};
    UAV(i).assignedDynamicTasks=[];
    assert(~isempty(UAV(i).path),'Missing initial waypoint path for UAV %d.',i);
end
end

function [Target,newTaskId]=appendDynamicTarget(Target,newTarget,cfg)
Target=normalizeTargetMatrix(Target,cfg);
row=zeros(1,size(Target,2));
copyCount=min(numel(newTarget),size(Target,2));
row(1:copyCount)=newTarget(1:copyCount);
if numel(newTarget)<5
    row(5)=cfg.dynamic.defaultTaskDueTime;
end
Target=[Target;row]; %#ok<AGROW>
newTaskId=size(Target,1)-1;
end


function Cost=expandCostMetadataOnDemand(Cost,Target,map,cfg)
% Expand the Cost container without planning any new inter-task path.
% New off-diagonal entries remain unknown (NaN/false/empty) until requested
% by an active insertion candidate.

positions=Target(:,1:3);
nOld=size(Cost.D,1);
nNew=size(positions,1);

if nNew<nOld
    error('simulateDynamicMission:CostShrink', ...
        'Online Cost cannot contain more nodes than the current Target array.');
end
if isfield(Cost,'TargetPosition') && nOld>0
    if ~isequaln(Cost.TargetPosition(1:nOld,:),positions(1:nOld,:))
        error('simulateDynamicMission:CostPrefixMismatch', ...
            'Existing Cost targets are not an unchanged prefix of Target.');
    end
end
if nNew==nOld
    return;
end

flightNodes=resolveFlightNodesLocal(positions,map,cfg);

nanFields={'D','E','T','DirectDistance','HorizontalDirectDistance', ...
    'AltitudeDifference','HorizontalDistance','VerticalDistance', ...
    'ClimbDistance','DescentDistance','MeanAbsSlopeDeg', ...
    'MeanClimbAngleDeg','MaxAbsSlopeDeg','NumWaypoints','PairRuntime', ...
    'ExpandedNodes','GeneratedNodes','ReopenedNodes','QueuePushes', ...
    'SearchIterations','SearchDistance','SearchScore'};
for q=1:numel(nanFields)
    f=nanFields{q};
    if isfield(Cost,f)
        old=Cost.(f);
        A=nan(nNew);
        A(1:nOld,1:nOld)=old;
        Cost.(f)=A;
    end
end

logicalFields={'Success','Failed'};
for q=1:numel(logicalFields)
    f=logicalFields{q};
    if isfield(Cost,f)
        old=logical(Cost.(f));
        A=false(nNew);
        A(1:nOld,1:nOld)=old;
        Cost.(f)=A;
    end
end

if isfield(Cost,'Paths')
    old=Cost.Paths;
    A=cell(nNew);
    A(1:nOld,1:nOld)=old;
    Cost.Paths=A;
else
    Cost.Paths=cell(nNew);
end
if isfield(Cost,'FailureMessage')
    old=Cost.FailureMessage;
    A=cell(nNew);
    A(1:nOld,1:nOld)=old;
    Cost.FailureMessage=A;
else
    Cost.FailureMessage=cell(nNew);
end

% Make sure the core fields exist even for a legacy Cost input.
coreNumeric={'D','E','T'};
for q=1:numel(coreNumeric)
    f=coreNumeric{q};
    if ~isfield(Cost,f)
        Cost.(f)=nan(nNew);
    end
end
if ~isfield(Cost,'Success'), Cost.Success=false(nNew); end
if ~isfield(Cost,'Failed'), Cost.Failed=false(nNew); end

Cost.TargetPosition=positions;
Cost.FlightNodePosition=flightNodes;
Cost.NodeCount=nNew;
Cost.MapSize=size(map);
Cost.MapResolution=cfg.map.resolution;
Cost.OnlineSparse=true;
Cost.OnlineCostMode='candidate-lazy-bound-cache';
if ~isfield(Cost,'OnlinePlanningRuntimeAccumulated')
    Cost.OnlinePlanningRuntimeAccumulated=0;
end
if ~isfield(Cost,'OnlineTaskEdgePlansAccumulated')
    Cost.OnlineTaskEdgePlansAccumulated=0;
end

% Diagonal entries represent zero-cost self transitions.
for j=1:nNew
    Cost.D(j,j)=0;
    Cost.E(j,j)=0;
    Cost.T(j,j)=0;
    Cost.Success(j,j)=true;
    Cost.Failed(j,j)=false;
    Cost.Paths{j,j}=flightNodes(j,:);
    Cost.FailureMessage{j,j}='';

    zeroDiag={'DirectDistance','HorizontalDirectDistance','AltitudeDifference', ...
        'HorizontalDistance','VerticalDistance','ClimbDistance','DescentDistance', ...
        'MeanAbsSlopeDeg','MeanClimbAngleDeg','MaxAbsSlopeDeg','PairRuntime', ...
        'ExpandedNodes','GeneratedNodes','ReopenedNodes','QueuePushes', ...
        'SearchIterations','SearchDistance','SearchScore'};
    for q=1:numel(zeroDiag)
        f=zeroDiag{q};
        if isfield(Cost,f), Cost.(f)(j,j)=0; end
    end
    if isfield(Cost,'NumWaypoints'), Cost.NumWaypoints(j,j)=1; end
end

% Straight-line metadata is cheap and may be populated for all new pairs.
for j=1:nNew
    for k=1:nNew
        if j==k, continue; end
        dr=(flightNodes(k,1)-flightNodes(j,1))*cfg.map.resolution;
        dc=(flightNodes(k,2)-flightNodes(j,2))*cfg.map.resolution;
        dz=flightNodes(k,3)-flightNodes(j,3);
        if isfield(Cost,'HorizontalDirectDistance')
            Cost.HorizontalDirectDistance(j,k)=hypot(dr,dc);
        end
        if isfield(Cost,'DirectDistance')
            Cost.DirectDistance(j,k)=hypot(hypot(dr,dc),dz);
        end
        if isfield(Cost,'AltitudeDifference')
            Cost.AltitudeDifference(j,k)=dz;
        end
    end
end

Cost=refreshOnlineCostBookkeeping(Cost);
end

function flightNodes=resolveFlightNodesLocal(positions,map,cfg)
n=size(positions,1);
flightNodes=zeros(n,3);
for j=1:n
    rc=round(positions(j,1:2));
    if rc(1)<1 || rc(1)>size(map,1) || rc(2)<1 || rc(2)>size(map,2)
        error('simulateDynamicMission:TargetOutsideMap', ...
            'Task node %d lies outside the DEM.',j-1);
    end
    terrain=map(rc(1),rc(2));
    z=min(max(positions(j,3),terrain+cfg.map.minClearance), ...
        terrain+cfg.map.maxClearance);
    flightNodes(j,:)=[rc,z];
end
end

function [Cost,info]=ensureTaskEdgeOnDemand(Cost,Target,fromTask,toTask,map,cfg)
% Return one directed task-to-task terrain edge, planning it only on a cache
% miss. Task IDs are public IDs (base=0); matrix nodes are taskID+1.

a=fromTask+1;
b=toTask+1;
info=struct('fromTask',fromTask,'toTask',toTask,'cacheHit',false, ...
    'planned',false,'knownFailure',false,'success',false, ...
    'runtimeS',0,'message','');

if a<1 || b<1 || a>size(Cost.D,1) || b>size(Cost.D,2)
    info.message='Requested task edge lies outside the current Cost matrix.';
    return;
end
if a==b
    info.cacheHit=true;
    info.success=true;
    return;
end

if Cost.Success(a,b) && isfinite(Cost.D(a,b)) && isfinite(Cost.T(a,b)) && ...
        ~isempty(Cost.Paths{a,b})
    info.cacheHit=true;
    info.success=true;
    return;
end
if isfield(Cost,'Failed') && Cost.Failed(a,b)
    info.knownFailure=true;
    if isfield(Cost,'FailureMessage') && ~isempty(Cost.FailureMessage{a,b})
        info.message=Cost.FailureMessage{a,b};
    else
        info.message='Previously failed terrain edge.';
    end
    return;
end

info.planned=true;
t=tic;
try
    R=planTerrainPath(Target(a,1:3),Target(b,1:3),map,cfg,false);
    info.runtimeS=toc(t);
    if ~logical(R.success)
        error('simulateDynamicMission:OnlinePathFailure', ...
            'DEMA* returned an unsuccessful edge %d -> %d.',fromTask,toTask);
    end

    Cost.D(a,b)=R.D;
    Cost.E(a,b)=R.E;
    Cost.T(a,b)=R.D/cfg.uav.speed;
    Cost.Paths{a,b}=R.path;
    Cost.Success(a,b)=true;
    Cost.Failed(a,b)=false;
    Cost.FailureMessage{a,b}='';

    m=R.metrics;
    metricMap={ ...
        'HorizontalDistance','horizontalLength'; ...
        'VerticalDistance','verticalDistance'; ...
        'ClimbDistance','climbDistance'; ...
        'DescentDistance','descentDistance'; ...
        'MeanAbsSlopeDeg','meanAbsSlopeDeg'; ...
        'MeanClimbAngleDeg','meanClimbAngleDeg'; ...
        'MaxAbsSlopeDeg','maxAbsSlopeDeg'; ...
        'NumWaypoints','numWaypoints'};
    for q=1:size(metricMap,1)
        f=metricMap{q,1}; src=metricMap{q,2};
        if isfield(Cost,f) && isfield(m,src)
            Cost.(f)(a,b)=m.(src);
        end
    end

    s=R.searchInfo;
    searchMap={ ...
        'ExpandedNodes','expandedNodes'; ...
        'GeneratedNodes','generatedNodes'; ...
        'ReopenedNodes','reopenedNodes'; ...
        'QueuePushes','queuePushes'; ...
        'SearchIterations','iterations'; ...
        'SearchDistance','finalSearchDistance'; ...
        'SearchScore','finalSearchScore'};
    for q=1:size(searchMap,1)
        f=searchMap{q,1}; src=searchMap{q,2};
        if isfield(Cost,f) && isfield(s,src)
            Cost.(f)(a,b)=s.(src);
        end
    end
    if isfield(Cost,'PairRuntime')
        if isfield(R,'runtime')
            Cost.PairRuntime(a,b)=R.runtime;
        else
            Cost.PairRuntime(a,b)=info.runtimeS;
        end
    end

    Cost.OnlinePlanningRuntimeAccumulated= ...
        Cost.OnlinePlanningRuntimeAccumulated+info.runtimeS;
    Cost.OnlineTaskEdgePlansAccumulated= ...
        Cost.OnlineTaskEdgePlansAccumulated+1;
    info.success=true;
catch ME
    info.runtimeS=toc(t);
    info.message=ME.message;
    Cost.Success(a,b)=false;
    Cost.Failed(a,b)=true;
    Cost.FailureMessage{a,b}=ME.message;
    if isfield(Cost,'PairRuntime'), Cost.PairRuntime(a,b)=info.runtimeS; end
end
end

function Cost=refreshOnlineCostBookkeeping(Cost)
n=size(Cost.D,1);
Cost.CompletedDirectedPairs=nnz(Cost.Success)-n;
Cost.TotalDirectedPairs=n*(n-1);
Cost.Summary=summarizeSparseOnlineCost(Cost);
end

function S=summarizeSparseOnlineCost(Cost)
mask=Cost.Success & ~eye(size(Cost.Success));
S=struct();
S.numNodes=size(Cost.D,1);
S.completedPairs=nnz(mask);
if isfield(Cost,'Failed')
    S.failedPairs=nnz(Cost.Failed & ~eye(size(Cost.Failed)));
else
    S.failedPairs=0;
end
if any(mask(:))
    S.meanDkm=mean(Cost.D(mask))/1000;
    S.meanEkJ=mean(Cost.E(mask))/1000;
    if isfield(Cost,'PairRuntime')
        vals=Cost.PairRuntime(mask & isfinite(Cost.PairRuntime));
        if isempty(vals), S.meanPairRuntimeS=NaN; else, S.meanPairRuntimeS=mean(vals); end
    else
        S.meanPairRuntimeS=NaN;
    end
    if isfield(Cost,'ExpandedNodes')
        vals=Cost.ExpandedNodes(mask & isfinite(Cost.ExpandedNodes));
        if isempty(vals), S.meanExpandedNodes=NaN; else, S.meanExpandedNodes=mean(vals); end
    else
        S.meanExpandedNodes=NaN;
    end
else
    S.meanDkm=NaN; S.meanEkJ=NaN; S.meanPairRuntimeS=NaN; S.meanExpandedNodes=NaN;
end

pairMask=triu(Cost.Success & Cost.Success.',1);
if any(pairMask(:))
    [ii,jj]=find(pairMask);
    dAbs=zeros(numel(ii),1); eAbs=zeros(numel(ii),1);
    dRel=zeros(numel(ii),1); eRel=zeros(numel(ii),1);
    for q=1:numel(ii)
        a=ii(q); b=jj(q);
        dAbs(q)=abs(Cost.D(a,b)-Cost.D(b,a));
        eAbs(q)=abs(Cost.E(a,b)-Cost.E(b,a));
        dDen=max((Cost.D(a,b)+Cost.D(b,a))/2,eps);
        eDen=max((Cost.E(a,b)+Cost.E(b,a))/2,eps);
        dRel(q)=100*dAbs(q)/dDen;
        eRel(q)=100*eAbs(q)/eDen;
    end
    S.meanDirectionalAsymmetryDm=mean(dAbs);
    S.maxDirectionalAsymmetryDm=max(dAbs);
    S.meanRelativeAsymmetryDPercent=mean(dRel);
    S.maxRelativeAsymmetryDPercent=max(dRel);
    S.meanDirectionalAsymmetryEJ=mean(eAbs);
    S.maxDirectionalAsymmetryEJ=max(eAbs);
    S.meanRelativeAsymmetryEPercent=mean(eRel);
    S.maxRelativeAsymmetryEPercent=max(eRel);
else
    S.meanDirectionalAsymmetryDm=NaN;
    S.maxDirectionalAsymmetryDm=NaN;
    S.meanRelativeAsymmetryDPercent=NaN;
    S.maxRelativeAsymmetryDPercent=NaN;
    S.meanDirectionalAsymmetryEJ=NaN;
    S.maxDirectionalAsymmetryEJ=NaN;
    S.meanRelativeAsymmetryEPercent=NaN;
    S.maxRelativeAsymmetryEPercent=NaN;
end
end

%% ========================================================================
%  Mission propagation
%  ========================================================================
function [uav,isComplete,sequence,Target,WayPoints]=advanceOneUAV( ...
    uav,sequence,Target,WayPoints,map,cfg)
% Advance one UAV by exactly v*Delta t metres along its 3-D waypoint path.
% Any unused distance after reaching a waypoint is carried into the next
% segment (and, if necessary, the next mission leg) within the same step.

isComplete=false;
travelBudgetM=cfg.uav.speed*cfg.dynamic.timeStep;

while travelBudgetM>1e-9 && ~isComplete
    path=uav.path;

    % Current leg finished: switch to the next edge of the current sequence.
    if uav.pathIndex>=size(path,1)
        uav.legIndex=uav.legIndex+1;
        if uav.legIndex>=numel(sequence)
            isComplete=true;
            break;
        end

        fromTask=sequence(uav.legIndex);
        toTask=sequence(uav.legIndex+1);
        fromNode=fromTask+1;
        toNode=toTask+1;
        uav.targetNode=toNode;

        if size(WayPoints,1)>=max(fromNode,toNode) && ...
                ~isempty(WayPoints{fromNode,toNode})
            uav.path=WayPoints{fromNode,toNode};
        else
            p=planTerrainPath(Target(fromNode,1:3),Target(toNode,1:3),map,cfg,false);
            uav.path=p.path;
            n=max([size(WayPoints,1),fromNode,toNode]);
            if size(WayPoints,1)<n
                tmp=cell(n,n);
                tmp(1:size(WayPoints,1),1:size(WayPoints,2))=WayPoints;
                WayPoints=tmp;
            end
            WayPoints{fromNode,toNode}=p.path;
        end
        uav.pathIndex=1;
        continue;
    end

    nextPoint=uav.path(uav.pathIndex+1,:);
    current=uav.currentPos;
    dRowM=(nextPoint(1)-current(1))*cfg.map.resolution;
    dColM=(nextPoint(2)-current(2))*cfg.map.resolution;
    dZM=nextPoint(3)-current(3);
    seg3D=hypot(hypot(dRowM,dColM),dZM);

    if seg3D<=1e-9
        uav.currentPos=nextPoint;
        uav.pathIndex=uav.pathIndex+1;
        continue;
    end

    if travelBudgetM>=seg3D
        uav.currentPos=nextPoint;
        uav.pathIndex=uav.pathIndex+1;
        travelBudgetM=travelBudgetM-seg3D;
    else
        ratio=travelBudgetM/seg3D;
        uav.currentPos=current+ratio*(nextPoint-current);
        travelBudgetM=0;
    end
end
end

%% ========================================================================
%  Terrain-aware insertion auction
%  ========================================================================
function [UAV,seq,event,Cost]=terrainAwareInsertionAuction( ...
    UAV,seq,Target,Cost,newTaskId,reachability,discoverer,complete,map,cfg,simTime)
% Event-driven local insertion auction with candidate-level lazy evaluation.
%
% v2.9.1 keeps the exact resource-aware bid and route write-back used in v2.7,
% fixes the remaining-route index passed to incremental after-task scoring,
% and avoids exact DEMA* evaluation of candidates that provably cannot beat
% the current incumbent. The online sequence is:
%   1) communication-reachable active UAV screening;
%   2) enumerate all insertion candidates without planning new terrain paths;
%   3) compute a cheap optimistic bid upper bound from 3-D straight-line
%      lower bounds and residual-resource upper bounds;
%   4) evaluate exact candidates in descending upper-bound order;
%   5) stop when every remaining upper bound is below the incumbent score;
%   6) cache every exact task-to-task terrain edge for future events.
%
% The pruning is exact with respect to the v2.7 objective because any
% terrain-following polyline is no shorter than the 3-D straight segment
% between the same endpoints. No Top-K heuristic cap is used.

n=numel(UAV);
newNode=newTaskId+1;
demand=Target(newNode,4);

reachableMask=logical(reachability(discoverer,:));
activeMask=~reshape(logical(complete),1,[]);
eligible=find(reachableMask & activeMask);

baselineByUAV=cell(1,n);
planning=initOnlinePlanningStats();
uavReachable=false(1,n);
uavHasFeasibleCandidate=false(1,n);
uavReachable(eligible)=true;

% -----------------------------------------------------------------------
% Stage 1: cheap candidate construction and optimistic upper bounds.
% -----------------------------------------------------------------------
lazyCandidates=repmat(emptyLazyCandidate(),0,1);
generationOrder=0;
optimisticEndurancePruned=0;

for ii=1:numel(eligible)
    i=eligible(ii);
    s=seq{i};

    if UAV(i).legIndex>=numel(s)
        continue;
    end

    baseline=computeCurrentRemainingSchedule(UAV(i),s,Target,Cost,simTime,cfg);
    baselineByUAV{i}=baseline;
    if ~baseline.valid
        continue;
    end

    UAV(i).remainTime=max(0,cfg.uav.maxEndurance-baseline.finishTimeS);

    residualCapacity=UAV(i).remainLoad-demand;
    payloadOK=residualCapacity>=-cfg.reallocation.feasibilityTolerance;
    if ~payloadOK
        continue;
    end

    currentIdx=UAV(i).legIndex+1;

    % Immediate diversion: current state -> new -> current target.
    if cfg.reallocation.allowImmediateDiversion
        generationOrder=generationOrder+1;
        currentTargetTask=s(currentIdx);
        dCurrentNewLB=currentToTaskStraightDistanceM( ...
            UAV(i).currentPos,newTaskId,Cost,Target,cfg);
        dNewTargetLB=taskDirectLowerBoundM( ...
            newTaskId,currentTargetTask,Cost,Target,cfg);
        deltaDLB=dCurrentNewLB+dNewTargetLB-baseline.firstLegDistanceM;

        d=makeLazyCandidate(i,'immediate',NaN,currentIdx,NaN, ...
            currentTargetTask,generationOrder,deltaDLB,residualCapacity, ...
            baseline,cfg);
        if d.optimisticFeasible
            lazyCandidates(end+1,1)=d; %#ok<AGROW>
        else
            d.status='pruned-optimistic-endurance';
            lazyCandidates(end+1,1)=d; %#ok<AGROW>
            optimisticEndurancePruned=optimisticEndurancePruned+1;
        end
    end

    % After-task insertions. Only the two new incident edges differ from
    % the validated baseline route, so their straight distances form a
    % lower bound on the exact insertion increment.
    for p=currentIdx:(numel(s)-1)
        generationOrder=generationOrder+1;
        fromTask=s(p);
        toTask=s(p+1);
        oldEdgeD=Cost.D(fromTask+1,toTask+1);
        if ~isfinite(oldEdgeD)
            % A currently executed/validated route should always have this
            % edge. If it does not, do not invent a bound from missing data.
            continue;
        end

        dA=taskDirectLowerBoundM(fromTask,newTaskId,Cost,Target,cfg);
        dB=taskDirectLowerBoundM(newTaskId,toTask,Cost,Target,cfg);
        deltaDLB=dA+dB-oldEdgeD;

        % IMPORTANT: currentTargetSeqIndex is the index of the UAV's
        % current target in the ORIGINAL remaining route. It must stay
        % equal to currentIdx for every insertion candidate. Using p+1 here
        % makes relFrom=0 in buildAfterTaskInsertionSchedule and falsely
        % marks every after-task candidate as infeasible.
        d=makeLazyCandidate(i,'after-task',p,currentIdx,fromTask,toTask, ...
            generationOrder,deltaDLB,residualCapacity,baseline,cfg);
        if d.optimisticFeasible
            lazyCandidates(end+1,1)=d; %#ok<AGROW>
        else
            d.status='pruned-optimistic-endurance';
            lazyCandidates(end+1,1)=d; %#ok<AGROW>
            optimisticEndurancePruned=optimisticEndurancePruned+1;
        end
    end
end

% Potential candidates are evaluated from largest optimistic bid to
% smallest. generationOrder breaks exact upper-bound ties reproducibly.
selectionPolicy='terrain-exact';
if isfield(cfg.reallocation,'selectionPolicy') && ...
        ~isempty(cfg.reallocation.selectionPolicy)
    selectionPolicy=lower(char(cfg.reallocation.selectionPolicy));
end
isCbbaEuclidean=strcmp(selectionPolicy,'cbba-euclidean');
if ~isCbbaEuclidean && ~strcmp(selectionPolicy,'terrain-exact')
    error('simulateDynamicMission:UnknownSelectionPolicy', ...
        'Unknown reallocation selection policy: %s',selectionPolicy);
end

potentialMask=[lazyCandidates.optimisticFeasible];
potentialIdx=find(potentialMask);
if isempty(potentialIdx)
    evalOrder=[];
else
    ub=[lazyCandidates(potentialIdx).optimisticScore].';
    go=[lazyCandidates(potentialIdx).generationOrder].';
    [~,ord]=sortrows([-ub,go],[1 2]);
    evalOrder=potentialIdx(ord);
end

% -----------------------------------------------------------------------
% Stage 2: lazy exact evaluation with branch-and-bound stopping.
% -----------------------------------------------------------------------
candidates=repmat(emptyCandidate(),0,1);
incumbentScore=-inf;
incumbentCandidate=[];
incumbentGenerationOrder=inf;
incumbentSelectionScore=-inf;
exactCandidateEvaluations=0;
boundPrunedCandidates=0;
boundStopUpperScore=NaN;
pruneTol=cfg.reallocation.lazyBoundTolerance;

for oo=1:numel(evalOrder)
    idxLazy=evalOrder(oo);
    ub=lazyCandidates(idxLazy).optimisticScore;

    % For one newly announced task, CBBA reduces to one best insertion bid
    % per reachable robot followed by consensus on the largest bid. This
    % baseline keeps the straight-line bid ranking fixed and validates bids
    % in that order until the first terrain-feasible insertion is found.
    if isCbbaEuclidean && ~isempty(incumbentCandidate)
        for rr=oo:numel(evalOrder)
            q=evalOrder(rr);
            lazyCandidates(q).status='not-evaluated-cbba-baseline';
        end
        break;
    end

    % Strict inequality preserves candidates that can still tie the
    % incumbent within numerical tolerance.
    if cfg.reallocation.lazyExactEvaluation && ...
            isfinite(incumbentScore) && ub < incumbentScore-pruneTol
        boundStopUpperScore=ub;
        for rr=oo:numel(evalOrder)
            q=evalOrder(rr);
            lazyCandidates(q).status='pruned-by-bound';
            boundPrunedCandidates=boundPrunedCandidates+1;
        end
        break;
    end

    d=lazyCandidates(idxLazy);
    exactCandidateEvaluations=exactCandidateEvaluations+1;
    [Cost,c,planning,exactStatus]=evaluateLazyCandidateExact( ...
        d,UAV,seq,Target,Cost,newTaskId,demand,baselineByUAV,map,cfg,simTime,planning);

    lazyCandidates(idxLazy).status=exactStatus;
    if strcmp(exactStatus,'exact-feasible')
        candidates(end+1,1)=c; %#ok<AGROW>
        uavHasFeasibleCandidate(c.uav)=true;
        lazyCandidates(idxLazy).exactScore=c.score;
        lazyCandidates(idxLazy).exactDeltaDistanceM=c.deltaDistanceM;
        lazyCandidates(idxLazy).exactDeltaLatenessS=c.deltaLatenessS;
        lazyCandidates(idxLazy).exactCandidateIndex=numel(candidates);
        lazyCandidates(idxLazy).upperBoundGap= ...
            lazyCandidates(idxLazy).optimisticScore-c.score;

        % Branch-and-bound correctness check. The exact bid must never
        % exceed the optimistic upper bound used for pruning. If this
        % assertion fails, pruning is disabled by stopping with a diagnostic
        % error rather than silently returning a potentially wrong winner.
        boundCheckTol=max(1e-8,100*pruneTol);
        if c.score > lazyCandidates(idxLazy).optimisticScore + boundCheckTol
            error('simulateDynamicMission:LazyBoundViolation', ...
                ['Exact bid %.12g exceeds optimistic upper bound %.12g ', ...
                 'for UAV %d candidate %s (%g -> %d -> %g).'], ...
                c.score,lazyCandidates(idxLazy).optimisticScore,c.uav,c.mode, ...
                c.insertAfterTask,newTaskId,c.insertBeforeTask);
        end

        tieTol=max(pruneTol,1e-12);
        if isCbbaEuclidean
            incumbentScore=c.score;
            incumbentCandidate=c;
            incumbentGenerationOrder=d.generationOrder;
            incumbentSelectionScore=ub;
        elseif c.score>incumbentScore+tieTol || ...
                (abs(c.score-incumbentScore)<=tieTol && ...
                 d.generationOrder<incumbentGenerationOrder)
            incumbentScore=c.score;
            incumbentCandidate=c;
            incumbentGenerationOrder=d.generationOrder;
            incumbentSelectionScore=c.score;
        end
    end
end

% Best exact insertion per UAV among candidates that needed evaluation.
% A UAV whose candidates were all pruned can remain -Inf here; its
% bidUpperBoundPerUAV still certifies that it cannot beat the winner.
bidsPerUAV=-inf(1,n);
bidUpperBoundPerUAV=-inf(1,n);
bestCandidateIndexPerUAV=nan(1,n);
for k=1:numel(lazyCandidates)
    i=lazyCandidates(k).uav;
    if lazyCandidates(k).optimisticFeasible && ...
            isfinite(lazyCandidates(k).optimisticScore)
        bidUpperBoundPerUAV(i)=max(bidUpperBoundPerUAV(i), ...
            lazyCandidates(k).optimisticScore);
    end
end
for k=1:numel(candidates)
    i=candidates(k).uav;
    if candidates(k).score>bidsPerUAV(i)
        bidsPerUAV(i)=candidates(k).score;
        bestCandidateIndexPerUAV(i)=k;
    end
end

winner=NaN;
selected=[];
if ~isempty(incumbentCandidate)
    selected=incumbentCandidate;
    winner=selected.uav;

    s=seq{winner};
    if strcmp(selected.mode,'immediate')
        insertAt=selected.currentTargetSeqIndex;
        s=[s(1:insertAt-1),newTaskId,s(insertAt:end)];
        UAV(winner).path=selected.diversionPath;
        UAV(winner).pathIndex=1;
        UAV(winner).targetNode=newNode;
        UAV(winner).targetTime=Target(newNode,5)*60-simTime;
    else
        p=selected.insertAfterSeqIndex;
        s=[s(1:p),newTaskId,s(p+1:end)];
    end
    seq{winner}=s;

    UAV(winner).remainLoad=selected.residualCapacityKg;
    UAV(winner).remainTime=selected.residualEnduranceS;
    UAV(winner).assignedDynamicTasks(end+1)=newTaskId;
end

Cost=refreshOnlineCostBookkeeping(Cost);

% -----------------------------------------------------------------------
% Event diagnostics.
% -----------------------------------------------------------------------
event=struct();
event.taskId=newTaskId;
event.selectionPolicy=selectionPolicy;
event.auctionSelectionScore=incumbentSelectionScore;
event.discoverer=discoverer;
event.reachableUAVs=eligible;
event.uavReachable=uavReachable;
event.uavHasFeasibleCandidate=uavHasFeasibleCandidate; % exact-evaluated only
event.uavHasPotentialCandidate=false(1,n);
for kk=1:numel(lazyCandidates)
    if lazyCandidates(kk).optimisticFeasible
        event.uavHasPotentialCandidate(lazyCandidates(kk).uav)=true;
    end
end
event.winner=winner;
event.bidsPerUAV=bidsPerUAV;
event.bidUpperBoundPerUAV=bidUpperBoundPerUAV;
event.bestCandidateIndexPerUAV=bestCandidateIndexPerUAV;
event.feasibleCandidateCount=numel(candidates); % exact-evaluated feasible candidates
event.exactFeasibleCandidateCount=numel(candidates);
event.totalEnumeratedCandidates=numel(lazyCandidates);
event.potentialCandidateCount=numel(evalOrder);
event.exactCandidateEvaluations=exactCandidateEvaluations;
event.boundPrunedCandidates=boundPrunedCandidates;
event.optimisticEndurancePrunedCandidates=optimisticEndurancePruned;
event.boundStopUpperScore=boundStopUpperScore;
exactGaps=[lazyCandidates.upperBoundGap];
exactGaps=exactGaps(isfinite(exactGaps));
if isempty(exactGaps)
    event.minUpperBoundGap=NaN;
else
    event.minUpperBoundGap=min(exactGaps);
end
if numel(evalOrder)>0
    event.exactEvaluationRatio=exactCandidateEvaluations/numel(evalOrder);
else
    event.exactEvaluationRatio=NaN;
end

if isempty(selected)
    event.assigned=false;
    event.score=-inf;
    event.insertMode='none';
    event.insertAfterTask=NaN;
    event.insertBeforeTask=NaN;
    event.selectedDeltaDistanceM=NaN;
    event.selectedDeltaEnergyJ=NaN;
    event.selectedDeltaLatenessS=NaN;
    event.selectedResidualCapacityKg=NaN;
    event.selectedResidualEnduranceS=NaN;
    event.baselineRemainingTimeS=NaN;
    event.proposedRemainingTimeS=NaN;
else
    event.assigned=true;
    event.score=selected.score;
    event.insertMode=selected.mode;
    event.insertAfterTask=selected.insertAfterTask;
    event.insertBeforeTask=selected.insertBeforeTask;
    event.selectedDeltaDistanceM=selected.deltaDistanceM;
    event.selectedDeltaEnergyJ=selected.deltaEnergyJ;
    event.selectedDeltaLatenessS=selected.deltaLatenessS;
    event.selectedResidualCapacityKg=selected.residualCapacityKg;
    event.selectedResidualEnduranceS=selected.residualEnduranceS;
    event.baselineRemainingTimeS=selected.baselineRemainingTimeS;
    event.proposedRemainingTimeS=selected.proposedRemainingTimeS;
end

if cfg.reallocation.storeCandidateDiagnostics
    event.candidateSet=stripCandidatePaths(candidates);
    event.candidateScreening=lazyCandidates;
else
    event.candidateSet=struct([]);
    event.candidateScreening=struct([]);
end

event.baselineByUAV=baselineByUAV;

% Online terrain-planning diagnostics.
event.costMode='candidate-lazy-bound-cache';
event.requestedTaskEdges=planning.requestedTaskEdges;
event.taskEdgeCacheHits=planning.taskEdgeCacheHits;
event.taskEdgePlans=planning.taskEdgePlans;
event.taskEdgePlanFailures=planning.taskEdgePlanFailures;
event.taskEdgePlanningRuntimeS=planning.taskEdgePlanningRuntimeS;
event.currentStateRequests=planning.currentStateRequests;
event.currentStatePlans=planning.currentStatePlans;
event.currentStatePlanFailures=planning.currentStatePlanFailures;
event.currentStatePlanningRuntimeS=planning.currentStatePlanningRuntimeS;
event.terrainPlanningRuntimeS=planning.taskEdgePlanningRuntimeS + ...
    planning.currentStatePlanningRuntimeS;
event.requestedTaskEdgeList=planning.requestedTaskEdgeList;
event.plannedTaskEdgeList=planning.plannedTaskEdgeList;
event.cacheHitTaskEdgeList=planning.cacheHitTaskEdgeList;
event.failedTaskEdgeList=planning.failedTaskEdgeList;
event.fullRowColumnEquivalentPairs=2*(size(Target,1)-1);
event.taskEdgePlansAvoided=max(0,event.fullRowColumnEquivalentPairs-event.taskEdgePlans);
if event.requestedTaskEdges>0
    event.taskEdgeCacheHitRatio=event.taskEdgeCacheHits/event.requestedTaskEdges;
else
    event.taskEdgeCacheHitRatio=NaN;
end
end

function d=emptyLazyCandidate()
d=struct( ...
    'uav',NaN, ...
    'mode','', ...
    'insertAfterSeqIndex',NaN, ...
    'currentTargetSeqIndex',NaN, ...
    'insertAfterTask',NaN, ...
    'insertBeforeTask',NaN, ...
    'generationOrder',NaN, ...
    'optimisticDeltaDistanceM',NaN, ...
    'optimisticResidualEnduranceS',NaN, ...
    'optimisticScore',-inf, ...
    'optimisticFeasible',false, ...
    'status','unevaluated', ...
    'exactScore',NaN, ...
    'exactDeltaDistanceM',NaN, ...
    'exactDeltaLatenessS',NaN, ...
    'exactCandidateIndex',NaN, ...
    'upperBoundGap',NaN);
end

function d=makeLazyCandidate(uavIndex,mode,insertAfterSeqIndex, ...
    currentTargetSeqIndex,insertAfterTask,insertBeforeTask,generationOrder, ...
    deltaDLB,residualCapacity,baseline,cfg)

d=emptyLazyCandidate();
d.uav=uavIndex;
d.mode=mode;
d.insertAfterSeqIndex=insertAfterSeqIndex;
d.currentTargetSeqIndex=currentTargetSeqIndex;
d.insertAfterTask=insertAfterTask;
d.insertBeforeTask=insertBeforeTask;
d.generationOrder=generationOrder;
d.optimisticDeltaDistanceM=deltaDLB;

finishLowerBound=baseline.finishTimeS + deltaDLB/cfg.uav.speed;
residualUpper=cfg.uav.maxEndurance-finishLowerBound;
% True residual endurance cannot exceed the full endurance budget. Capping
% only tightens the optimistic bound and remains valid.
residualUpper=min(cfg.uav.maxEndurance,residualUpper);
d.optimisticResidualEnduranceS=residualUpper;
d.optimisticFeasible=residualUpper>=-cfg.reallocation.feasibilityTolerance;

Dref=max(cfg.reallocation.distanceRefM,eps);
capacityTerm=max(0,residualCapacity)/cfg.uav.capacity;
enduranceTerm=max(0,residualUpper)/cfg.uav.maxEndurance;
% Incremental lateness is nonnegative in the score through max(0,DeltaL),
% so zero is the most optimistic possible lateness penalty.
d.optimisticScore= ...
    -cfg.reallocation.wDistance*(deltaDLB/Dref) + ...
     cfg.reallocation.wCapacity*capacityTerm + ...
     cfg.reallocation.wEndurance*enduranceTerm;
end

function [Cost,c,planning,status]=evaluateLazyCandidateExact( ...
    d,UAV,seq,Target,Cost,newTaskId,demand,baselineByUAV,map,cfg,simTime,planning)

c=emptyCandidate();
status='exact-path-failure';
i=d.uav;
baseline=baselineByUAV{i};

if isempty(baseline) || ~baseline.valid
    status='exact-invalid-baseline';
    return;
end

if strcmp(d.mode,'immediate')
    currentTargetTask=d.insertBeforeTask;
    [Cost,edgeInfo]=ensureTaskEdgeOnDemand( ...
        Cost,Target,newTaskId,currentTargetTask,map,cfg);
    planning=accumulateTaskEdgeStats(planning,edgeInfo);
    if ~edgeInfo.success
        return;
    end

    planning.currentStateRequests=planning.currentStateRequests+1;
    try
        diversion=planCurrentToDynamicTask( ...
            UAV(i).currentPos,Target(newTaskId+1,1:3),map,cfg);
        planning.currentStatePlans=planning.currentStatePlans+1;
        planning.currentStatePlanningRuntimeS= ...
            planning.currentStatePlanningRuntimeS+diversion.runtimeS;
    catch ME
        planning.currentStatePlanFailures=planning.currentStatePlanFailures+1;
        status='exact-current-path-failure';
        if cfg.plot.verbose
            fprintf('  UAV %d immediate-diversion path unavailable: %s\n',i,ME.message);
        end
        return;
    end

    s=seq{i};
    currentIdx=d.currentTargetSeqIndex;
    remainingIds=[newTaskId,s(currentIdx:end)];
    proposed=buildScheduleFromCurrent(diversion.D,diversion.E,diversion.T, ...
        remainingIds,Target,Cost,simTime,cfg);

    c=makeCandidate(i,'immediate',NaN,currentIdx,newTaskId, ...
        baseline,proposed,UAV(i),demand,cfg);
    c.insertAfterTask=NaN;
    c.insertBeforeTask=currentTargetTask;
    c.diversionPath=diversion.path;
    c.diversionPlanningRuntimeS=diversion.runtimeS;
else
    fromTask=d.insertAfterTask;
    toTask=d.insertBeforeTask;

    [Cost,edgeA]=ensureTaskEdgeOnDemand( ...
        Cost,Target,fromTask,newTaskId,map,cfg);
    planning=accumulateTaskEdgeStats(planning,edgeA);
    if ~edgeA.success
        return;
    end

    [Cost,edgeB]=ensureTaskEdgeOnDemand( ...
        Cost,Target,newTaskId,toTask,map,cfg);
    planning=accumulateTaskEdgeStats(planning,edgeB);
    if ~edgeB.success
        return;
    end

    p=d.insertAfterSeqIndex;
    proposed=buildAfterTaskInsertionSchedule(baseline,d,newTaskId, ...
        Target,Cost,simTime,cfg);

    c=makeCandidate(i,'after-task',p,d.currentTargetSeqIndex,newTaskId, ...
        baseline,proposed,UAV(i),demand,cfg);
    c.insertAfterTask=fromTask;
    c.insertBeforeTask=toTask;
end

if c.feasible
    status='exact-feasible';
else
    status='exact-infeasible';
end
end

function d=taskDirectLowerBoundM(fromTask,toTask,Cost,Target,cfg)
a=fromTask+1;
b=toTask+1;
if isfield(Cost,'DirectDistance') && ...
        a>=1 && b>=1 && a<=size(Cost.DirectDistance,1) && ...
        b<=size(Cost.DirectDistance,2) && isfinite(Cost.DirectDistance(a,b))
    d=Cost.DirectDistance(a,b);
    return;
end

% Fallback uses the same endpoint projection convention as the Cost library.
if isfield(Cost,'FlightNodePosition') && ...
        a<=size(Cost.FlightNodePosition,1) && b<=size(Cost.FlightNodePosition,1)
    p1=Cost.FlightNodePosition(a,:);
    p2=Cost.FlightNodePosition(b,:);
else
    p1=Target(a,1:3);
    p2=Target(b,1:3);
end
dRow=(p2(1)-p1(1))*cfg.map.resolution;
dCol=(p2(2)-p1(2))*cfg.map.resolution;
dZ=p2(3)-p1(3);
d=hypot(hypot(dRow,dCol),dZ);
end


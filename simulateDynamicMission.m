function S=accumulateTaskEdgeStats(S,info)
S.requestedTaskEdges=S.requestedTaskEdges+1;
S.requestedTaskEdgeList(end+1,:)=[info.fromTask,info.toTask]; %#ok<AGROW>
if info.cacheHit
    S.taskEdgeCacheHits=S.taskEdgeCacheHits+1;
    S.cacheHitTaskEdgeList(end+1,:)=[info.fromTask,info.toTask]; %#ok<AGROW>
end
if info.planned
    if info.success
        S.taskEdgePlans=S.taskEdgePlans+1;
        S.plannedTaskEdgeList(end+1,:)=[info.fromTask,info.toTask]; %#ok<AGROW>
    else
        S.taskEdgePlanFailures=S.taskEdgePlanFailures+1;
        S.failedTaskEdgeList(end+1,:)=[info.fromTask,info.toTask]; %#ok<AGROW>
    end
    S.taskEdgePlanningRuntimeS=S.taskEdgePlanningRuntimeS+info.runtimeS;
elseif info.knownFailure
    S.taskEdgePlanFailures=S.taskEdgePlanFailures+1;
    S.failedTaskEdgeList(end+1,:)=[info.fromTask,info.toTask]; %#ok<AGROW>
end
end

